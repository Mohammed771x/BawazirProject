import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';
import 'package:wordos/app/wordos_app.dart';
import 'package:wordos/core/api/api_providers.dart';
import 'package:wordos/core/storage/app_preferences.dart';
import 'package:wordos/core/storage/preferences_providers.dart';
import 'package:wordos/core/storage/token_store.dart';
import 'package:wordos/core/widgets/app_widgets.dart';

/// The whole journey, driven through the real UI against the real stack:
/// Flutter → ASP.NET Core → Python → Gemini → PostgreSQL and back.
///
/// Nothing here is stubbed. The passages are generated by Gemini, the words come
/// out of the imported lexicon, and every pass/fail is the backend's decision —
/// which is the point: this is the only test that can prove the wire contract,
/// the models and the screens agree with each other.
///
/// Run with:
/// ```
/// flutter test integration_test/real_backend_journey_test.dart \
///   -d <device> --dart-define=WORDOS_MOCK=false \
///   --dart-define=WORDOS_API_BASE_URL=http://127.0.0.1:5199/api
/// ```
void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  // A fresh learner per run, so the journey always starts at onboarding and
  // never depends on what an earlier run left behind.
  final email = 'journey-${DateTime.now().millisecondsSinceEpoch}@wordos.test';
  const password = 'correct-horse-battery';

  testWidgets('a new learner goes from registration to a finished session',
      (tester) async {
    await _boot(tester);

    // ── 1. Registration ──────────────────────────────────────────────────
    expect(find.text('Welcome back'), findsOneWidget,
        reason: 'the app should open on sign-in');

    await _tapText(tester, 'Create account');

    // By position: the label lives in the field's decoration, so matching on it
    // is brittle, and the form is name → email → password.
    await _fillAt(tester, 0, 'Layla');
    await _fillAt(tester, 1, email);
    await _fillAt(tester, 2, password);
    await _tapButton(tester, 'Create account');
    await _settle(tester);

    // ── 2. Interests ─────────────────────────────────────────────────────
    expect(find.textContaining('interest'), findsWidgets,
        reason: 'registration should land on the interests step');

    // The chips read "💻  Technology", so the match has to be on a substring.
    for (final interest in ['Technology', 'Science', 'Travel']) {
      final chip = find.textContaining(interest);
      if (chip.evaluate().isNotEmpty) {
        await tester.tap(chip.first, warnIfMissed: false);
        await tester.pump(const Duration(milliseconds: 150));
      }
    }

    await _tapAny(tester, ['Continue', 'Save', 'Next']);
    await _settle(tester);

    // Continue is disabled until something is picked, so a tap that "worked"
    // is not proof the step advanced.
    expect(find.text('What interests you?'), findsNothing,
        reason: 'saving interests should leave the interests step. '
            'Visible: ${_visibleText(tester)}');

    // ── 3. Placement ─────────────────────────────────────────────────────
    //
    // Adaptive: the number of questions depends on the answers, so the test
    // answers whatever it is shown until the test ends itself.
    await _tapAny(tester, ['Start', 'Start test', 'Begin']);
    await _settle(tester);

    var answered = 0;
    while (answered < 40) {
      // The result screen ends the test, however many questions it took —
      // the count is adaptive and deliberately not fixed.
      if (find.text('Start learning').evaluate().isNotEmpty) break;

      final options = find.byType(OptionTile);
      if (options.evaluate().isNotEmpty) {
        // A long passage pushes the options below the fold, and a tap that
        // lands outside the viewport does nothing at all.
        await tester.ensureVisible(options.first);
        await tester.pump(const Duration(milliseconds: 100));
        await tester.tap(options.first);
      } else if (find.byType(TextField).evaluate().isNotEmpty) {
        // Tapped first, then typed. The screen clears the controller between
        // questions, which drops the test input connection — typing into it
        // without re-focusing silently emits no `onChanged`, leaving the Next
        // button disabled with no visible sign of why.
        await tester.ensureVisible(find.byType(TextField).first);
        await tester.tap(find.byType(TextField).first);
        await tester.pump(const Duration(milliseconds: 150));
        await tester.enterText(
            find.byType(TextField).first,
            'Yesterday I studied for about $answered hours and then I read a '
            'long article about science before going out with my friends.');
      } else {
        fail('placement showed neither options nor a text field. '
            'Visible: ${_visibleText(tester)}');
      }
      await tester.pump(const Duration(milliseconds: 150));

      await _tapAny(tester, ['Next']);
      await _settle(tester);
      answered++;
    }

    debugPrint('✓ placement answered $answered questions');

    // The result screen reports a level per skill, and Spelling must not carry
    // one (ADR-008) — worth checking here, where it is the real server's answer.
    expect(find.text('Start learning'), findsOneWidget,
        reason: 'placement should finish. Visible: ${_visibleText(tester)}');

    await _tapText(tester, 'Start learning');
    await _settle(tester);

    expect(_isOnHub(tester), isTrue,
        reason: 'placement should end on the Skills Hub. '
            'Visible: ${_visibleText(tester)}');
    debugPrint('✓ reached the Skills Hub');

    // ── 4. Add a word from the real lexicon ──────────────────────────────
    await _tapAny(tester, ['Add word', 'Add a word', 'Add']);
    await _settle(tester);

    await tester.tap(find.byType(TextField).first);
    await tester.pump(const Duration(milliseconds: 150));
    // A prefix, not a whole word: this is the autocomplete the demo review
    // asked for — `res` should surface `research` with its Arabic meaning.
    await tester.enterText(find.byType(TextField).first, 'research');
    await _settle(tester);

    // Candidates are AppCards, one per sense — `research` has several, which is
    // the point: the learner picks the meaning, and that choice is the word's
    // identity (ADR-012).
    final candidates = find.byWidgetPredicate(
        (w) => w is AppCard && w.onTap != null);

    expect(candidates, findsWidgets,
        reason: 'the lexicon should offer senses for "research". '
            'Visible: ${_visibleText(tester)}');

    // Each candidate carries the Arabic meaning of that specific sense — the
    // client never invents one (ADR-012).
    expect(_visibleText(tester).any(_hasArabic), isTrue,
        reason: 'candidates should show Arabic meanings');

    await tester.ensureVisible(candidates.first);
    await tester.tap(candidates.first);
    await tester.pump(const Duration(milliseconds: 200));
    await _tapAny(tester, ['Add word', 'Add', 'Save']);
    await _settle(tester);
    debugPrint('✓ added a word from the lexicon');

    // ── 5. A real Reading session ────────────────────────────────────────
    await _goToHub(tester);
    await _tapText(tester, 'Reading');
    await _settle(tester, total: const Duration(seconds: 90));

    // The passage is written by Gemini, so its wording is unknown — but a real
    // passage has to be there, and it has to contain the word being taught.
    final passage = _visibleText(tester)
        .firstWhere((t) => t.length > 150, orElse: () => '');

    expect(passage, isNotEmpty,
        reason: 'a reading session should show a generated passage. '
            'Visible: ${_visibleText(tester).take(4)}');
    expect(passage.toLowerCase(), contains('research'),
        reason: 'the passage should actually use the target word');
    debugPrint('✓ Gemini passage (${passage.length} chars): '
        '${passage.substring(0, passage.length.clamp(0, 120))}…');

    // Reading is content-first: the questions only appear once the learner says
    // they have finished reading.
    await _tapAny(tester, ['I finished reading']);
    await _settle(tester);

    // Work through the questions. The answers are unknown to the client — that
    // is the point — so it picks the first option each time and lets the server
    // decide, including requeueing anything it got wrong.
    var steps = 0;
    var requeued = 0;
    while (steps < 60) {
      if (find.text('Session complete').evaluate().isNotEmpty) break;

      final options = find.byType(OptionTile);
      if (options.evaluate().isNotEmpty) {
        await tester.ensureVisible(options.first);
        await tester.tap(options.first);
        await tester.pump(const Duration(milliseconds: 150));
      }

      if (!await _tapAnyIfPresent(tester, ['Check', 'Next', 'Continue', 'Finish'])) {
        break;
      }
      await _settle(tester, total: const Duration(seconds: 60));

      // A wrong answer is explained rather than just marked (§28) — the server
      // sends the explanation, the client only shows it.
      if (_visibleText(tester).any((t) => t.contains(' means '))) requeued++;

      steps++;
    }

    debugPrint('✓ worked through the session in $steps steps '
        '($requeued explanations shown)');

    expect(find.text('Session complete'), findsWidgets,
        reason: 'the session should reach its result. '
            'Visible: ${_visibleText(tester).take(6)}');

    // ── 6. The outcome is the server's ───────────────────────────────────
    //
    // The test answers by always taking the first option, so it mostly answers
    // wrongly — and the result must say the word is coming back rather than
    // dropping it. Wrong is never discarded (§48).
    final resultText = _visibleText(tester).join(' | ');
    expect(resultText, contains('research'),
        reason: 'the result should name the word it practised');
    expect(
        resultText.contains('another try') || resultText.contains('Listening'),
        isTrue,
        reason: 'the word should either advance or be scheduled again, never '
            'vanish. Visible: $resultText');

    // Arabic meanings on the result screen come from the lexicon, via the
    // server — more evidence the whole chain is real.
    expect(_visibleText(tester).any(_hasArabic), isTrue);
    debugPrint('✓ result: ${resultText.substring(0, resultText.length.clamp(0, 160))}');

    // ── 7. Weekly review — measurement only ──────────────────────────────
    await _tapAny(tester, ['Back to Skills Hub']);
    await _settle(tester);

    if (await _tapAnyIfPresent(tester, ['Weekly review', 'Weekly Review'])) {
      await _settle(tester);
      await _tapAnyIfPresent(tester, ['Start', 'Begin']);
      await _settle(tester);

      var reviewSteps = 0;
      while (reviewSteps < 20) {
        final options = find.byType(OptionTile);
        if (options.evaluate().isEmpty) break;
        await tester.ensureVisible(options.first);
        await tester.tap(options.first);
        await tester.pump(const Duration(milliseconds: 150));
        if (!await _tapAnyIfPresent(tester, ['Check', 'Next', 'Finish'])) break;
        await _settle(tester);
        reviewSteps++;
      }
      debugPrint('✓ weekly review answered $reviewSteps items');
    }
  }, timeout: const Timeout(Duration(minutes: 12)));

  testWidgets('a session survives the app being killed', (tester) async {
    // The second app launch is a genuinely cold one: a fresh widget tree and a
    // fresh token store, exactly like a relaunch. What survives is what the
    // server remembers (rule R4), so this is the real test of recovery.
    final store = _MemoryTokenStore();
    await _boot(tester, store: store);

    await _tapText(tester, 'Create account');
    final email2 = 'resume-${DateTime.now().millisecondsSinceEpoch}@wordos.test';
    await _fillAt(tester, 0, 'Omar');
    await _fillAt(tester, 1, email2);
    await _fillAt(tester, 2, password);
    await _tapButton(tester, 'Create account');
    await _settle(tester);

    // Straight past onboarding — this test is about recovery, not placement.
    for (final interest in ['Technology', 'Science']) {
      final chip = find.textContaining(interest);
      if (chip.evaluate().isNotEmpty) {
        await tester.tap(chip.first, warnIfMissed: false);
        await tester.pump(const Duration(milliseconds: 150));
      }
    }
    await _tapAny(tester, ['Continue']);
    await _settle(tester);
    await _skipPlacement(tester);

    // Add a word and start a session.
    await _tapAny(tester, ['Add word', 'Add a word', 'Add']);
    await _settle(tester);
    await tester.tap(find.byType(TextField).first);
    await tester.pump(const Duration(milliseconds: 150));
    await tester.enterText(find.byType(TextField).first, 'theory');
    await _settle(tester);

    final candidate =
        find.byWidgetPredicate((w) => w is AppCard && w.onTap != null);
    await tester.ensureVisible(candidate.first);
    await tester.tap(candidate.first);
    await tester.pump(const Duration(milliseconds: 200));
    await _tapAny(tester, ['Add word', 'Add', 'Save']);
    await _settle(tester);

    await _goToHub(tester);
    await _tapText(tester, 'Reading');
    await _settle(tester, total: const Duration(seconds: 90));

    final firstPassage = _visibleText(tester)
        .firstWhere((t) => t.length > 150, orElse: () => '');
    expect(firstPassage, isNotEmpty);

    await _tapAny(tester, ['I finished reading']);
    await _settle(tester);

    // Answer one question, then leave — as a learner does when the phone rings.
    final options = find.byType(OptionTile);
    await tester.ensureVisible(options.first);
    await tester.tap(options.first);
    await tester.pump(const Duration(milliseconds: 150));
    await _tapAny(tester, ['Check', 'Next']);
    await _settle(tester);

    await tester.pageBack();
    await _settle(tester);

    // ── Relaunch ─────────────────────────────────────────────────────────
    //
    // A new widget tree and a new provider scope: every screen re-fetches over
    // HTTP, and the only thing carried across is the token store — the same two
    // values the real app keeps in the keystore.
    //
    // The app's navigator uses a library-level GlobalKey, so its route stack
    // outlives `pumpWidget` and a literal process kill cannot be staged here.
    // What this does prove is the part that matters: nothing about the session
    // is held on the device, so recovery depends entirely on what the server
    // remembers.
    await _boot(tester, store: store);
    expect(_isOnHub(tester), isTrue,
        reason: 'the stored token should sign the learner straight back in. '
            'Visible: ${_visibleText(tester)}');

    await _tapText(tester, 'Reading');
    await _settle(tester, total: const Duration(seconds: 90));

    // Resuming drops the learner back on the questions, not on the passage:
    // the server reports how many items are already answered, so the reading
    // step is behind them.
    expect(find.text('I finished reading'), findsNothing,
        reason: 'a resumed session should not send the learner back to the '
            'passage. Visible: ${_visibleText(tester).take(6)}');
    expect(find.byType(OptionTile), findsWidgets,
        reason: 'a resumed session should show the next question. '
            'Visible: ${_visibleText(tester).take(6)}');

    // And it is the same session, not a fresh one: the question count includes
    // the item already cleared before the relaunch.
    final progress = _visibleText(tester)
        .firstWhere((t) => RegExp(r'\d+\s*/\s*\d+').hasMatch(t),
            orElse: () => '');
    debugPrint('✓ resumed on question "$progress" '
        '(original passage was ${firstPassage.length} chars)');
  }, timeout: const Timeout(Duration(minutes: 12)));
}

// ── Helpers ──────────────────────────────────────────────────────────────────

/// Runs the placement test with whatever answers come to hand — this is a
/// precondition for other tests, not the thing under test.
Future<void> _skipPlacement(WidgetTester tester) async {
  await _tapAny(tester, ['Start', 'Start test', 'Begin']);
  await _settle(tester);

  for (var i = 0; i < 40; i++) {
    if (find.text('Start learning').evaluate().isNotEmpty) break;

    final options = find.byType(OptionTile);
    if (options.evaluate().isNotEmpty) {
      await tester.ensureVisible(options.first);
      await tester.tap(options.first);
    } else if (find.byType(TextField).evaluate().isNotEmpty) {
      await tester.ensureVisible(find.byType(TextField).first);
      await tester.tap(find.byType(TextField).first);
      await tester.pump(const Duration(milliseconds: 150));
      await tester.enterText(find.byType(TextField).first,
          'I read about this topic for roughly \$i hours last week at home.');
    }
    await tester.pump(const Duration(milliseconds: 150));
    if (!await _tapAnyIfPresent(tester, ['Next'])) break;
    await _settle(tester);
  }

  await _tapAny(tester, ['Start learning']);
  await _settle(tester);
}

Future<void> _boot(WidgetTester tester, {TokenStore? store}) async {
  await tester.pumpWidget(
    ProviderScope(
      overrides: [
        // Only the two device-owned settings are overridden, and only so the
        // assertions can be written in English. Everything else — the API, the
        // tokens, the whole backend — is real.
        appPreferencesProvider.overrideWithValue(
            InMemoryAppPreferences(locale: const Locale('en'))),
        // Passing the same store across two `_boot` calls is what makes the
        // second one a relaunch rather than a new install: the tokens persist,
        // everything else starts from nothing.
        tokenStoreProvider.overrideWith((ref) => store ?? _MemoryTokenStore()),
      ],
      // A fresh key on every boot. Without it Flutter sees the same
      // `const WordOsApp()` and reuses the existing element tree, so the
      // "relaunch" would keep the previous screen and prove nothing.
      child: KeyedSubtree(
        key: ValueKey('boot-${_bootCount++}'),
        child: const WordOsApp(),
      ),
    ),
  );
  await _settle(tester);
}

int _bootCount = 0;

/// `pumpAndSettle` gives up on a screen with a running animation, and a Gemini
/// call takes seconds — so time is advanced in slices instead.
Future<void> _settle(
  WidgetTester tester, {
  Duration total = const Duration(seconds: 45),
}) async {
  final deadline = DateTime.now().add(total);
  while (DateTime.now().isBefore(deadline)) {
    await tester.pump(const Duration(milliseconds: 250));
    if (!_isBusy(tester)) {
      // One more frame, so a just-arrived response gets painted.
      await tester.pump(const Duration(milliseconds: 250));
      return;
    }
  }
}

bool _isBusy(WidgetTester tester) =>
    find.byType(CircularProgressIndicator).evaluate().isNotEmpty;

/// Arabic meanings must come from the server, so seeing Arabic on screen is a
/// meaningful check that the lexicon reached the client.
bool _hasArabic(String text) =>
    RegExp(r'[؀-ۿ]').hasMatch(text);

/// Returns to the hub from wherever the journey currently is.
Future<void> _goToHub(WidgetTester tester) async {
  for (var i = 0; i < 4 && !_isOnHub(tester); i++) {
    if (!await _tapAnyIfPresent(tester, ['Skills', 'Back to skills', 'Done'])) {
      final back = find.byTooltip('Back');
      if (back.evaluate().isEmpty) break;
      await tester.tap(back.first);
    }
    await _settle(tester);
  }
}

bool _isOnHub(WidgetTester tester) =>
    find.text('Reading').evaluate().isNotEmpty &&
    find.text('Listening').evaluate().isNotEmpty;

Future<void> _fillAt(WidgetTester tester, int index, String value) async {
  final fields = find.byType(TextFormField);
  expect(fields.evaluate().length, greaterThan(index),
      reason: 'expected at least ${index + 1} text fields on this screen');
  await tester.enterText(fields.at(index), value);
  await tester.pump(const Duration(milliseconds: 100));
}

Future<void> _tapText(WidgetTester tester, String text) async {
  await tester.tap(find.text(text).first);
  await _settle(tester);
}

Future<void> _tapButton(WidgetTester tester, String label) async {
  final button = find.widgetWithText(FilledButton, label);
  await tester.tap(button.evaluate().isNotEmpty ? button.first : find.text(label).first);
  await tester.pump(const Duration(milliseconds: 200));
}

Future<void> _tapAny(WidgetTester tester, List<String> labels) async {
  if (!await _tapAnyIfPresent(tester, labels)) {
    fail('none of $labels was on screen. Visible text: ${_visibleText(tester)}');
  }
}

/// Every string currently rendered — the fastest way to see where a journey
/// actually stopped, rather than guessing at a label.
///
/// `RichText` is included deliberately: the reading passage highlights its
/// target words with spans, so it is a `RichText` and not a `Text`, and leaving
/// it out makes the passage invisible to the test.
List<String> _visibleText(WidgetTester tester) => [
      ...tester
          .widgetList<Text>(find.byType(Text))
          .map((t) => t.data ?? t.textSpan?.toPlainText() ?? ''),
      ...tester
          .widgetList<RichText>(find.byType(RichText))
          .map((t) => t.text.toPlainText()),
    ].where((s) => s.trim().isNotEmpty).toList();

Future<bool> _tapAnyIfPresent(WidgetTester tester, List<String> labels) async {
  for (final label in labels) {
    final found = find.text(label);
    if (found.evaluate().isEmpty) continue;
    await tester.tap(found.first, warnIfMissed: false);
    await tester.pump(const Duration(milliseconds: 200));
    return true;
  }
  return false;
}

/// The keystore is unavailable under `flutter test`; tokens live in memory for
/// the run, which is all the journey needs.
class _MemoryTokenStore extends TokenStore {
  String? _token;
  String? _refresh;

  @override
  String? get token => _token;

  @override
  String? get refreshToken => _refresh;

  @override
  Future<String?> restore() async => _token;

  @override
  Future<void> save(String token, {String? refreshToken}) async {
    _token = token;
    if (refreshToken != null) _refresh = refreshToken;
  }

  @override
  Future<void> clear() async {
    _token = null;
    _refresh = null;
  }
}
